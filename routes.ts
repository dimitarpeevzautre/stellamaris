export const isIndexable = (route: RouteDef): boolean => route.indexable !== false;

export const getRoute = (id: RouteId): AppRoute => {
  const route = ROUTES.find((r) => r.id === id);
  if (!route) throw new Error(`Unknown route id: ${id}`);
  return route;
};

/** Prefix a language-neutral path ('/about/') for a language ('/bg/about/'). */
export const localizePath = (path: string, lang: Language): string => `${LANGUAGE_PREFIX[lang]}${path}`;

/** Path of a route in a language, always with a trailing slash. */
export const routePath = (id: RouteId, lang: Language): string => localizePath(getRoute(id).path, lang);

export const absoluteUrl = (path: string): string => `${SITE_URL}${path}`;

const withTrailingSlash = (path: string): string => (path.endsWith('/') ? path : `${path}/`);

export interface LocationMatch {
  lang: Language;
  /** The matched route, or null when the path is not a known page (404). */
  route: AppRoute | null;
}

/** Resolve a URL pathname to its language and route. Pure: safe on server and client. */
export const matchPath = (pathname: string): LocationMatch => {
  let lang: Language = DEFAULT_LANGUAGE;
  let rest = pathname || '/';
  for (const candidate of LANGUAGES) {
    const prefix = LANGUAGE_PREFIX[candidate];
    if (prefix && (rest === prefix || rest.startsWith(`${prefix}/`))) {
      lang = candidate;
      rest = rest.slice(prefix.length) || '/';
      break;
    }
  }
  // /index.html and /about/index.html are served by static hosting too: treat them as / and /about/.
  const normalized = withTrailingSlash(rest.replace(/\/index\.html$/, '/'));
  const route = ROUTES.find((r) => r.path === normalized) ?? null;
  return { lang, route };
};

/**
 * Where the language switcher should point: the same page in `lang`, or that
 * language's home page when the current path is not a known page.
 */
export const switchLanguagePath = (pathname: string, lang: Language): string => {
  const { route } = matchPath(pathname);
  return route ? routePath(route.id, lang) : routePath('home', lang);
};

/**
 * Map a URL from the old HashRouter site ('#/puppies?x=1') to its new path
 * ('/puppies/?x=1'). Returns null when the hash is not an old route link.
 */
export const legacyHashToPath = (hash: string): string | null => {
  if (!hash.startsWith('#/')) return null;
  const raw = hash.slice(1);
  const queryIndex = raw.indexOf('?');
  const pathname = queryIndex === -1 ? raw : raw.slice(0, queryIndex);
  const search = queryIndex === -1 ? '' : raw.slice(queryIndex);
  const { lang, route } = matchPath(pathname);
  return `${route ? routePath(route.id, lang) : routePath('home', lang)}${search}`;
};
