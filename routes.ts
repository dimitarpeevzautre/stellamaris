export interface RouteDef {
  /** Stable identifier used in code (e.g. `routePath('contact', lang)`). */
  readonly id: string;
  /** Language-neutral path with leading and trailing slash, e.g. '/about/'. */
  readonly path: string;
  /** Component file name in pages/ without extension, e.g. 'About' → pages/About.tsx. */
  readonly page: string;
  /** Translation key of the main-navigation label. Omit to keep the page out of the nav. */
  readonly navKey?: string;
  /** Per-language <title> and meta description. */
  readonly meta: Readonly<Record<Language, PageMeta>>;
  /** High-priority image preloads emitted only on this route (LCP hints). */
  readonly preloadImages?: readonly PreloadImage[];
  /** Set to false to exclude from the sitemap and mark the page noindex. Defaults to true. */
  readonly indexable?: boolean;
}

